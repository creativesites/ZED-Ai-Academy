"""Regenerate src/app/app-surface-reset.css from public/assets/css/bootstrap.min.css.

Bootstrap 5 utilities are `!important` and share names with Tailwind classes. Inside `.app-surface`
(and portalled dialogs/menus) we roll each of those declarations back with `revert-layer` so the
layered Tailwind utility wins. Run: python3 scripts/gen-app-surface-reset.py
"""
import re

SRC = "public/assets/css/bootstrap.min.css"
OUT = "src/app/app-surface-reset.css"
SCOPE = ':is(.app-surface, [data-slot="dialog-content"], [data-slot="dropdown-menu-content"], [data-slot="sheet-content"])'


def top_level_rules(css):
    rules, j = [], 0
    while j < len(css):
        if css.startswith("@", j):
            k = css.index("{", j) + 1
            depth = 1
            while depth:
                depth += {"{": 1, "}": -1}.get(css[k], 0)
                k += 1
            j = k
            continue
        k = css.find("{", j)
        if k < 0:
            break
        e = css.index("}", k)
        rules.append((css[j:k].strip(), css[k + 1 : e]))
        j = e + 1
    return rules


props = {}
for sel, body in top_level_rules(open(SRC).read()):
    if "!important" not in body:
        continue
    for s in sel.split(","):
        m = re.fullmatch(r"\.([a-z0-9\-]+)", s.strip())
        if not m:
            continue
        for decl in body.split(";"):
            if "!important" in decl and ":" in decl:
                prop = decl.split(":")[0].strip()
                if not prop.startswith("--"):
                    props.setdefault(m.group(1), set()).add(prop)

lines = [
    "/*",
    " * GENERATED by scripts/gen-app-surface-reset.py from public/assets/css/bootstrap.min.css.",
    " * Bootstrap 5 utilities use !important and share names with Tailwind classes (p-5, gap-3, border,",
    " * rounded, shadow-sm, text-center, w-100, …). Inside app surfaces, roll them back so Tailwind wins.",
    " */",
]
for cls in sorted(props):
    decls = " ".join(f"{p}: revert-layer !important;" for p in sorted(props[cls]))
    lines.append(f"{SCOPE} .{cls} {{ {decls} }}")
open(OUT, "w").write("\n".join(lines) + "\n")
print(f"wrote {OUT} ({len(props)} classes)")
